/**
 * Writes src/lib/currencies.ts: every active ISO 4217 currency with its English name, symbol,
 * decimals and the unit word used in copy ("Every peso in and out").
 * Built from Node's Intl once and committed, because Hermes' Intl data differs by platform.
 * Run with `npm run currencies`.
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const outFile = path.join(root, 'src/lib/currencies.ts');

/** Not money people budget in, or replaced by another code (HRK, BGN → EUR; ANG → XCG; …). */
const EXCLUDE = new Set(['XDR', 'XSU', 'SLL', 'ZWL', 'HRK', 'BGN', 'ANG', 'CUC']);

/**
 * ISO 4217 currencies with no minor unit. Intl's own digits follow cash rounding (IDR, HUF, PKR
 * show 0 there), so ISO is the source; everything else is 2 (3-decimal currencies capped at 2).
 */
const ZERO_DECIMALS = new Set([
  'BIF', 'CLP', 'DJF', 'GNF', 'ISK', 'JPY', 'KMF', 'KRW', 'PYG', 'RWF', 'UGX', 'VND', 'VUV', 'XAF', 'XOF', 'XPF',
]);

/** Symbols Intl's `en` narrow symbol gets wrong for us. */
const SYMBOL_OVERRIDES = { PHP: '₱' };

/** Unit words that aren't simply the last word of the name. */
const UNIT_OVERRIDES = { ZWG: 'ZiG' };

/** Hebrew and Arabic script ranges. */
const RTL = /[\u0590-\u08FF\uFB1D-\uFDFF\uFE70-\uFEFF]/;

const names = new Intl.DisplayNames('en', { type: 'currency' });

const currencies = Intl.supportedValuesOf('currency')
  .filter((code) => !EXCLUDE.has(code))
  .map((code) => {
    const narrow =
      SYMBOL_OVERRIDES[code] ??
      new Intl.NumberFormat('en', { style: 'currency', currency: code, currencyDisplay: 'narrowSymbol' })
        .formatToParts(1)
        .find((p) => p.type === 'currency').value;
    // A right-to-left symbol (AFN ؋) flips the direction of the whole line: use the code instead.
    const symbol = RTL.test(narrow) ? code : narrow;
    // Sentence case like the mockup ("Philippine peso"): the unit word is lowercased, proper
    // adjectives keep their capitals. A one-word name ("Euro") stays as is.
    const words = names.of(code).split(' ');
    const last = words[words.length - 1];
    const name = words.length > 1 ? [...words.slice(0, -1), last.toLowerCase()].join(' ') : words[0];
    const unit = UNIT_OVERRIDES[code] ?? last.toLowerCase();
    return { code, name, symbol, digits: ZERO_DECIMALS.has(code) ? 0 : 2, unit };
  })
  .sort((a, b) => a.name.localeCompare(b.name, 'en'));

const rows = currencies.map((c) => `  ${JSON.stringify(c)},`).join('\n');

const source = `// Generated by scripts/build-currencies.mjs (\`npm run currencies\`). Do not edit by hand.

export type Currency = {
  /** ISO 4217 code, e.g. "PHP". */
  code: string;
  /** English name in sentence case, e.g. "Philippine peso". */
  name: string;
  /** Narrow symbol, e.g. "₱"; the code itself when there is no short symbol. */
  symbol: string;
  /** Decimals shown and accepted: 0 (JPY, KRW…) or 2. Storage is always hundredths. */
  digits: 0 | 2;
  /** Singular word for copy, e.g. "peso" ("Every peso in and out"). */
  unit: string;
};

export const DEFAULT_CURRENCY_CODE = 'PHP';

/** Every active ISO 4217 currency, sorted by name. */
export const CURRENCIES: readonly Currency[] = [
${rows}
];

const byCode = new Map(CURRENCIES.map((c) => [c.code, c]));

/** The currency for a code, or undefined when it isn't in the list. */
export function findCurrency(code: string | null | undefined): Currency | undefined {
  return code ? byCode.get(code) : undefined;
}

export const DEFAULT_CURRENCY = byCode.get(DEFAULT_CURRENCY_CODE)!;
`;

await writeFile(outFile, source);
console.log(`Wrote ${currencies.length} currencies to ${path.relative(root, outFile)}`);
